package org.javahelpers.simple.builders.processor.mapstruct;

import com.google.auto.service.AutoService;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import javax.lang.model.element.AnnotationMirror;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.TypeElement;
import javax.lang.model.type.DeclaredType;
import javax.lang.model.type.TypeMirror;
import javax.lang.model.util.Elements;
import org.javahelpers.simple.builders.core.annotations.Ignore4BuilderGeneration;
import org.javahelpers.simple.builders.core.annotations.SimpleBuilder;
import org.javahelpers.simple.builders.processor.SimpleBuildersSpiIntegration;
import org.javahelpers.simple.builders.processor.SimpleBuildersSpiIntegration.PublishedBuilder;
import org.javahelpers.simple.builders.processor.SimpleBuildersSpiIntegration.State;
import org.javahelpers.simple.builders.processor.analysis.JavaLangAnalyser;
import org.mapstruct.ap.spi.BuilderInfo;
import org.mapstruct.ap.spi.BuilderProvider;
import org.mapstruct.ap.spi.MapStructProcessingEnvironment;
import org.mapstruct.ap.spi.TypeHierarchyErroneousException;

/**
 * MapStruct {@link BuilderProvider} SPI that makes MapStruct use builders generated by
 * simple-builders.
 *
 * <p>MapStruct's default provider only considers {@code public static} methods on the bean type
 * itself as builder-creation candidates. simple-builders keeps the factory on the generated builder
 * class ({@code PersonDtoBuilder.create()}), so beans are paired with builders exclusively through
 * the registry {@code BuilderProcessor} publishes — a constant-time lookup of already-resolved
 * {@link PublishedBuilder} descriptors (builder type, creation and build method, setter suffix),
 * covering custom packages and {@code @SimpleBuilderFor} targets. Builders produced by earlier
 * compilations are not discovered: only the beans the processor plans in the current run get
 * builder mapping.
 *
 * <p>{@code BuilderProcessor} generates in exactly one round — the first round carrying its
 * annotations — and marks the registry final when it ends. A lookup miss before that point defers
 * the mapper via {@link TypeHierarchyErroneousException}, MapStruct's own retry mechanism, for
 * every bean: no bean-side marker is needed, so {@code @SimpleBuilderFor} targets resolve too. Once
 * final, a miss is definitive: a bean marked for generation is reported as a warning, a foreign
 * bean just maps without a builder. A published builder whose type is not emitted yet defers until
 * the registry is final.
 *
 * <p>The provider is registered via {@code META-INF/services} and is only loaded when
 * simple-builders-processor and mapstruct-processor share the annotation processor path. The
 * integration can be switched off entirely with {@code
 * -Asimplebuilder.usingMapStructIntegration=DISABLED} or the {@code -D} JVM system property — the
 * {@code -A} argument reaches SPI environments because {@link
 * MapStructAdditionalSupportedOptionsProvider} declares it.
 */
@AutoService(BuilderProvider.class)
public class MapStructBuilderProvider implements BuilderProvider {

  private Elements elementUtils;
  private Map<String, String> processorOptions = Map.of();

  /** Resolved builder infos by bean qualified name; only positive results are cached. */
  private final Map<String, BuilderInfo> builderInfoCache = new HashMap<>();

  @Override
  public void init(MapStructProcessingEnvironment processingEnvironment) {
    this.elementUtils = processingEnvironment.getElementUtils();
    Map<String, String> options = processingEnvironment.getOptions();
    processorOptions = options == null ? Map.of() : options;
  }

  @Override
  public BuilderInfo findBuilderInfo(TypeMirror type) {
    if (!SimpleBuildersSpiIntegration.isMapstructGenerationEnabled(processorOptions)) {
      return null;
    }
    if (!(type instanceof DeclaredType declaredType)
        || !(declaredType.asElement() instanceof TypeElement beanElement)) {
      return null;
    }
    BuilderInfo cached = builderInfoCache.get(beanElement.getQualifiedName().toString());
    if (cached != null) {
      return cached;
    }
    BuilderInfo builderInfo = createBuilderInfo(beanElement);
    if (builderInfo != null) {
      builderInfoCache.put(beanElement.getQualifiedName().toString(), builderInfo);
    }
    return builderInfo;
  }

  /**
   * Resolves the generated builder for {@code beanElement} through the registry {@code
   * BuilderProcessor} publishes — the list decides alone which type is claimed.
   */
  private BuilderInfo createBuilderInfo(TypeElement beanElement) {
    Optional<PublishedBuilder> published = publishedFor(beanElement);
    TypeElement builderElement = findBuilderElement(beanElement, published);
    if (builderElement == null) {
      return null;
    }
    ExecutableElement creationMethod = creationMethod(builderElement, published.orElseThrow());
    Optional<ExecutableElement> buildMethod = buildMethod(builderElement, published.orElseThrow());
    if (creationMethod == null || buildMethod.isEmpty()) {
      return null;
    }
    return new BuilderInfo.Builder()
        .builderCreationMethod(creationMethod)
        .buildMethod(List.of(buildMethod.orElseThrow()))
        .build();
  }

  /**
   * The element of the builder published for {@code beanElement}, waiting for a pending
   * registration or emission via {@link TypeHierarchyErroneousException} — MapStruct's own deferral
   * mechanism. {@code null} for foreign beans and for misses that are definitive.
   */
  private TypeElement findBuilderElement(
      TypeElement beanElement, Optional<PublishedBuilder> published) {
    if (published.isEmpty()) {
      if (state() != State.FINISHED) {
        // The generating round may not have run yet — any bean may still be registered, so
        // defer the mapper for a retry once the registry is final.
        throw new TypeHierarchyErroneousException(beanElement.asType());
      }
      // The registry is final: a marked bean without an entry was skipped by planning.
      if (isBuilderGenerationTarget(beanElement)) {
        warnMarkedBeanWithoutRegisteredBuilder(beanElement);
      }
      return null;
    }
    TypeElement builderElement =
        elementUtils.getTypeElement(published.get().builderType().getFullQualifiedName());
    if (builderElement == null) {
      // The type is written with the generating round's sources and materializes in the next
      // round — defer until it exists.
      throw new TypeHierarchyErroneousException(beanElement.asType());
    }
    return builderElement;
  }

  /**
   * The state of the compilation this provider's {@code elementUtils} belongs to — {@link
   * State#INIT} while the holder still describes a previous run on a reused JVM.
   */
  private State state() {
    return SimpleBuildersSpiIntegration.isCurrentCompilation(elementUtils)
        ? SimpleBuildersSpiIntegration.state()
        : State.INIT;
  }

  /**
   * The builder published for {@code beanElement} — empty while the holder still describes a
   * previous run, so stale entries can never claim a bean.
   */
  private Optional<PublishedBuilder> publishedFor(TypeElement beanElement) {
    return SimpleBuildersSpiIntegration.isCurrentCompilation(elementUtils)
        ? SimpleBuildersSpiIntegration.builderFor(beanElement.getQualifiedName().toString())
        : Optional.empty();
  }

  /** Warns that a bean marked for generation got no registered builder in this compilation. */
  private void warnMarkedBeanWithoutRegisteredBuilder(TypeElement beanElement) {
    // SPI environments expose no Messager — a logger is the only channel a build shows.
    System.getLogger(MapStructBuilderProvider.class.getName())
        .log(
            System.Logger.Level.WARNING,
            "simple-builders: no generated builder was registered for the marked bean '"
                + beanElement.getQualifiedName()
                + "'; MapStruct maps it without a builder.");
  }

  /**
   * The published creation method on the resolved builder — a {@code public static} parameterless
   * factory whose name the descriptor carries ({@code create} for generated builders).
   */
  private ExecutableElement creationMethod(TypeElement builderElement, PublishedBuilder published) {
    return JavaLangAnalyser.findMethodWithoutParameters(
            builderElement, published.creationMethodName(), Modifier.PUBLIC, Modifier.STATIC)
        .orElse(null);
  }

  /**
   * The published build method on the resolved builder — the {@code public} parameterless instance
   * method named by the descriptor ({@code build} for generated builders).
   */
  private Optional<ExecutableElement> buildMethod(
      TypeElement builderElement, PublishedBuilder published) {
    return JavaLangAnalyser.findMethodWithoutParameters(
        builderElement, published.buildMethodName(), Modifier.PUBLIC);
  }

  /**
   * Whether {@code beanElement} is marked for builder generation ({@code @SimpleBuilder} or a
   * builder template annotation, not opted out via {@code @Ignore4BuilderGeneration}). The marker
   * only decides the finished-state warning — deferral and claiming never depend on it.
   */
  private boolean isBuilderGenerationTarget(TypeElement beanElement) {
    if (JavaLangAnalyser.findAnnotation(beanElement, Ignore4BuilderGeneration.class).isPresent()) {
      return false;
    }
    if (JavaLangAnalyser.findAnnotation(beanElement, SimpleBuilder.class).isPresent()) {
      return true;
    }
    for (AnnotationMirror mirror : beanElement.getAnnotationMirrors()) {
      // A custom builder template annotation (e.g. @SimpleMinimalBuilder or a project-defined
      // one): its type is meta-annotated with @SimpleBuilder.Template.
      if (mirror.getAnnotationType().asElement() instanceof TypeElement annotationType
          && JavaLangAnalyser.findAnnotation(annotationType, SimpleBuilder.Template.class)
              .isPresent()) {
        return true;
      }
    }
    return false;
  }
}
